#!/usr/bin/env python3
"""Install, check or remove nstack.

  python3 install.py              back up, then install (idempotent); ends with --check
  python3 install.py --check      verify the installed state; exit 1 on any problem
  python3 install.py --uninstall  remove nstack and restore what the first install replaced
  python3 install.py --no-dross   leave Dross's home AGENTS.md alone (combines with the above)

What it manages:
  ~/.omp/agent/skills/<name>              symlinks to skills/<name>; other nstack* skills are removed
  ~/.omp/agent/commands/<name>.md         symlinks to commands/*.md (nstack, bro)
  ~/.omp/agent/commands/<name>/index.ts   symlinks to commands/<name>/index.ts (improve), in a real directory because
                                          omp skips symlinked command directories
  ~/.omp/agent/extensions/nstack-guard.ts symlink to extensions/nstack-guard.ts
  ~/.omp/agent/agents/<name>.md           one per roster agent, generated from roster.toml and agents/*.md
  ~/.omp/agent/AGENTS.md                  the "Subagent routing" section, generated from roster.toml
  ~/.omp/agent/RULES.md                   marked block from omp-rules.md (always applied by omp)
  $DROSS_HOME/home/AGENTS.md              marked block from dross.md, with the roster's worker models (Context's live home:
                                          DROSS_HOME, else ~/.context-dross, as LIVE_HOME in its apps/dross/src/config.ts)

roster.toml is nstack's only model input; Context Models Settings may generate it. Rerun this script to render it.
Before the first install changes anything, every managed path is copied to local/backups/baseline/
with manifest.json; --uninstall restores from it. Every later install also writes a dated backup.
"""
import json, os, re, shutil, subprocess, sys, tempfile, time, tomllib
from fnmatch import fnmatchcase
from pathlib import Path

REPO = Path(__file__).resolve().parent
ROSTER = REPO / "roster.toml"
CATALOG = None
HOME = Path.home()
OMP = HOME / ".omp" / "agent"
SKILLS = OMP / "skills"
COMMANDS = OMP / "commands"
AGENT_DIR = OMP / "agents"
EXTENSION = OMP / "extensions" / "nstack-guard.ts"
RULES = OMP / "RULES.md"
OMP_AGENTS = OMP / "AGENTS.md"
DROSS_AGENTS = Path(os.environ.get("DROSS_HOME") or HOME / ".context-dross").resolve() / "home" / "AGENTS.md"
CONTRACTS = [HOME / "Projects/context-wt/next/apps/core/src/factory/context.contract.json",
             HOME / "Projects/context/apps/core/src/factory/context.contract.json"]
BACKUPS = REPO / "local" / "backups"
BASELINE = BACKUPS / "baseline"
BEGIN, END = "<!-- nstack:begin -->", "<!-- nstack:end -->"
BLOCK = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
GENERATED = "# Generated by ~/Projects/nstack/install.py from roster.toml. Change models in Context Settings."
ROUTING_HEADING = "# Subagent routing"
# Context embeds each standard whole (never clipped) in a worker's 32k-token pack. 12,000 chars (about 3k tokens)
# keeps any one standard under a tenth of that pack; it is a pack-fit check, not a target to fill.
MAX_STANDARD_CHARS = 12000
ROLES = ("author", "systems", "taste", "implementer", "reader", "research", "verify")
JUDGMENT_ROLES = ("author", "systems", "taste")
# Roles whose agents use their own template; every other agent is an author.
TEMPLATE_ROLES = {"reader": "reader", "research": "researcher", "verify": "verifier"}


# ---------- roster ----------

def load_roster():
    return tomllib.loads(ROSTER.read_text())


def names_in(r, roles):
    return list(dict.fromkeys(n for role in roles for n in r["roles"][role]["agents"]))


def template_role(r, name):
    return next((role for role in TEMPLATE_ROLES if name in r["roles"][role]["agents"]), "author")


def described(r, name):
    a = r["agents"][name]
    return f"`{name}` ({a['label']}" + (f"; {a['note']}" if a.get("note") else "") + ")"


def either(items):
    items = list(items)
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " or " + items[-1]


def reviewers(r):
    """reviewer -> the authors whose work it reviews: the first judgment agent of another family."""
    judges = names_in(r, JUDGMENT_ROLES)
    out = {}
    for name in r["agents"]:
        if template_role(r, name) != "author":
            continue
        family = r["agents"][name]["family"]
        reviewer = next((j for j in judges if r["agents"][j]["family"] != family), None)
        if reviewer:
            out.setdefault(reviewer, []).append(name)
    return out


def roster_problems(r):
    problems = []
    agents, roles = r.get("agents", {}), r.get("roles", {})
    for role in ROLES:
        entry = roles.get(role)
        if not entry or not entry.get("agents") or not entry.get("title") or not entry.get("does"):
            problems.append(f"roster: role {role} needs title, does and at least one agent")
            continue
        problems += [f"roster: role {role} lists unknown agent {n}" for n in entry["agents"] if n not in agents]
    for name, a in agents.items():
        problems += [f"roster: agent {name} lacks {k}" for k in ("model", "label", "family", "thinking") if not a.get(k)]
        own = [role for role in TEMPLATE_ROLES if name in roles.get(role, {}).get("agents", [])]
        builds = [role for role in ROLES if role not in TEMPLATE_ROLES and name in roles.get(role, {}).get("agents", [])]
        if len(own) > 1 or (own and builds):
            problems.append(f"roster: agent {name} is in {own + builds}; readers, research and verify agents hold one role only")
    return problems


# ---------- rendering ----------

def agent_file(r, name):
    a, roles = r["agents"][name], r["roles"]
    held = [role for role in ROLES if name in roles[role]["agents"]]
    does = "; ".join(f"{roles[x]['title'].lower()}: {roles[x]['does']}" for x in held) or "only when Nate names it"
    note = f" ({a['note']})" if a.get("note") else ""
    head = [GENERATED, f"name: {name}", "description: " + json.dumps(f"{a['label']}{note} — {does}", ensure_ascii=False),
            f"model: {a['model']}", f"thinkingLevel: {a['thinking']}"]
    role = template_role(r, name)
    if role == "author":
        readers, lanes = names_in(r, ("reader",)), names_in(r, ("research", "verify"))
        head += ["autoloadSkills: [nstack]", "spawns:"] + [f"  - {n}" for n in readers + lanes]
        body = (REPO / "agents" / "author.md").read_text()
        body = body.replace("{readers}", ", ".join(readers)).replace("{research}", ", ".join(lanes))
    elif role == "reader":
        head += ["spawns: []"]
        body = (REPO / "agents" / "reader.md").read_text()
    else:
        template = (REPO / "agents" / f"{TEMPLATE_ROLES[role]}.md").read_text()
        extra, body = re.match(r"---\n(.*?)\n---\n(.*)", template, re.S).groups()
        head += extra.splitlines()
    return "---\n" + "\n".join(head) + "\n---\n\n" + body.lstrip("\n")


def routing(r):
    agents, roles = r["agents"], r["roles"]
    lines = [ROUTING_HEADING, "",
             "Generated from Nate's model roster (`~/Projects/nstack/roster.toml`), projected by Context Models Settings. "
             "Change models and allowed models in that page or Dross's models tool; never hand-edit generated files.", "",
             "Spawn subagents only through these agents with the `task` tool, and set `agent` on every task item. "
             "Never use disabled, bundled or built-in agents, and never another model or provider unless Nate names it; "
             "this applies to nested delegation too.", "",
             "## Roles", ""]
    for role in ROLES:
        entry = roles[role]
        lines.append(f"- {entry['title']}: {', '.join(described(r, n) for n in entry['agents'])}. "
                     f"{entry['does'][0].upper()}{entry['does'][1:]}.")
    unassigned = [n for n in agents if not any(n in roles[x]["agents"] for x in ROLES)]
    if unassigned:
        lines.append(f"- Only when Nate names it: {', '.join(described(r, n) for n in unassigned)}.")
    pairs = "; ".join(f"{either(f'`{n}`' for n in authors)} work goes to `{rev}`" for rev, authors in reviewers(r).items())
    if not pairs:
        pairs = "no judgment model of another family is assigned"
    levels = {}
    for name, a in agents.items():
        levels.setdefault(a["thinking"], []).append(f"`{name}`")
    defaults = "; ".join(f"{level} for {', '.join(names)}" for level, names in levels.items())
    lines += ["",
              "Authors (every agent except the readers, research and verify agents) load `skill://nstack` automatically "
              "and delegate only to the readers and research workers unless their brief grants more. Research and "
              "verification lanes run only through `skill://research`.", "",
              "## Delegation and reviews", "",
              "nstack decides how to delegate (`skill://nstack`, `skill://nstack-agents`): agents where they add quality "
              "(parallel slices with disjoint files, bulk reading and research width, races between models on an open "
              "shape, critics on real artifacts), each run with control. Pick the author by role, never by price.", "",
              f"Critics come from a judgment model of another family: {pairs}. One critic for a large, one-way-door or "
              "risky change (security, data loss, money, migration) or when Nate asks; a second only when it asks a "
              "different question (correctness, maintainability, the real surface). Never a critic of a critic. A race "
              "(several models on one brief, judged blind by another family) is for an open shape; taste directions "
              "from several models go to Nate to pick.", "",
              "## Reasoning effort", "",
              f"Default effort, from the roster: {defaults}. A task item's `effort` overrides it: `hi` is the model's top "
              "level up to `task.maxEffort`, `med` its middle, and `lo` its lowest. Use `hi` when the work has open judgment: a cause or design still "
              "open, a one-way door, taste-critical work, a review of a risky change, or reading that must judge rather "
              "than extract. Use `lo` only for fully mechanical work whose check would catch any slip. Otherwise omit it. "
              "Never lower effort to save tokens."]
    return "\n".join(lines)


def dross_models(r):
    agents, roles = r["agents"], r["roles"]
    model = lambda n: f"`{agents[n]['model']}` ({n})"
    author, taste, systems = (roles[x]["agents"][0] for x in ("author", "taste", "systems"))
    parts = [f"{model(author)} by default" + (" and for taste-critical work" if taste == author else "")]
    if taste != author:
        parts.append(f"{model(taste)} for taste-critical work")
    parts += [f"{model(systems)} for hard systems work",
              f"{either(model(n) for n in roles['implementer']['agents'])} for {roles['implementer']['title'].lower()} "
              f"({roles['implementer']['does']})"]
    review = "; ".join(f"{either(authors)} work by {rev}" for rev, authors in reviewers(r).items())
    return (f"- Worker models, from Nate's roster (`~/Projects/nstack/roster.toml`; this overrides any other model list "
            f"in this file): {'; '.join(parts)}; anything else only when Nate names it. A review of a worker's change "
            f"comes from the other family: {review}.")


def wrap(text):
    return f"{BEGIN}\n{text.strip()}\n{END}"


def rendered(source, r):
    return wrap((REPO / source).read_text().replace("{{worker_models}}", dross_models(r)))


# ---------- files ----------

def upsert_block(path, block, anchor=None):
    text = path.read_text() if path.exists() else ""
    if BLOCK.search(text):
        text = BLOCK.sub(lambda _: block, text, count=1)
    elif anchor and anchor in text:
        text = text.replace(anchor, f"\n{block}\n{anchor}", 1)
    else:
        text = (text.rstrip() + "\n\n" if text.strip() else "") + block + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def section_span(text, heading):
    """Start and end of a top-level section: from its heading to the next `# ` heading."""
    m = re.search(r"^" + re.escape(heading) + r"[ \t]*$", text, re.M)
    if not m:
        return None
    nxt = re.search(r"^# ", text[m.end():], re.M)
    return m.start(), (m.end() + nxt.start() if nxt else len(text))


def upsert_section(path, block, heading):
    """Replace an earlier nstack block, else the hand-written section with that heading, else prepend."""
    text = path.read_text() if path.exists() else ""
    if BLOCK.search(text):
        text = BLOCK.sub(lambda _: block, text, count=1)
    else:
        span = section_span(text, heading)
        text = (text[:span[0]] + block + "\n\n" + text[span[1]:].lstrip("\n")) if span else block + "\n\n" + text
    path.write_text(text)


def remove_block(path, replacement=""):
    if path.exists():
        path.write_text(re.sub(r"\n?" + BLOCK.pattern + r"\n?", lambda _: replacement, path.read_text(), flags=re.S))


def present(path):
    return path.exists() or path.is_symlink()


def remove(path):
    if path.is_dir() and not path.is_symlink():
        shutil.rmtree(path)
    elif present(path):
        path.unlink()


def copy(src, dst):
    dst.parent.mkdir(parents=True, exist_ok=True)
    if src.is_dir() and not src.is_symlink():
        shutil.copytree(src, dst, symlinks=True)
    else:
        shutil.copy2(src, dst, follow_symlinks=False)


def links():
    """(installed path, repo source) for every symlink nstack owns."""
    return ([(SKILLS / p.name, p) for p in sorted((REPO / "skills").iterdir()) if (p / "SKILL.md").is_file()]
            + [(COMMANDS / p.name, p) for p in sorted((REPO / "commands").glob("*.md"))]
            + [(COMMANDS / p.parent.name / p.name, p) for p in sorted((REPO / "commands").glob("*/index.ts"))]
            + [(EXTENSION, REPO / "extensions" / "nstack-guard.ts")])


def generated(path):
    return path.is_file() and path.read_text().startswith(f"---\n{GENERATED}\n")


def stale_agents(r):
    return [p for p in AGENT_DIR.glob("*.md") if p.stem not in r["agents"] and generated(p)]


def backup(dross, r):
    """Copy every path an install may replace. The first backup is the baseline uninstall restores."""
    targets = ([p for p, _ in links()] + list(SKILLS.glob("nstack*")) + [AGENT_DIR / f"{n}.md" for n in r["agents"]]
               + [RULES, OMP_AGENTS] + ([DROSS_AGENTS] if dross else []))
    BACKUPS.mkdir(parents=True, exist_ok=True)
    first = not (BASELINE / "manifest.json").exists()
    dest = BASELINE if first else Path(tempfile.mkdtemp(prefix=time.strftime("%Y%m%d-%H%M%S-"), dir=BACKUPS))
    dest.mkdir(exist_ok=True)
    manifest = {}
    for p in dict.fromkeys(targets):
        name = str(p.relative_to(HOME)).replace("/", "__").lstrip(".")
        manifest[str(p)] = name if present(p) else None
        if present(p):
            copy(p, dest / name)
    (dest / "manifest.json").write_text(json.dumps(manifest, indent=1))
    return dest


# ---------- commands ----------

def install(dross):
    r = load_roster()
    problems = roster_problems(r) or model_problems(r) + config_problems(r, [])
    if problems:
        sys.exit("\n".join(f"FAIL {p}" for p in problems) + "\nnothing installed")
    dest = backup(dross, r)
    names = [p.name for p, _ in links() if p.parent == SKILLS]
    for old in SKILLS.glob("nstack*"):
        if old.name not in names:
            remove(old)
    for path, source in links():
        remove(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.symlink_to(source)
    AGENT_DIR.mkdir(parents=True, exist_ok=True)
    for name in r["agents"]:
        (AGENT_DIR / f"{name}.md").write_text(agent_file(r, name))
    for p in stale_agents(r):
        p.unlink()
    upsert_section(OMP_AGENTS, wrap(routing(r)), ROUTING_HEADING)
    upsert_block(RULES, rendered("omp-rules.md", r))
    if dross and DROSS_AGENTS.exists():
        upsert_block(DROSS_AGENTS, rendered("dross.md", r), anchor="\n## Email")
    print(f"installed {', '.join(names)} and agents {', '.join(r['agents'])}; backup at {dest}")


def uninstall(dross):
    for path, source in links():
        if path.is_symlink() and path.resolve() == source.resolve():
            path.unlink()
            if path.parent.parent == COMMANDS and not any(path.parent.iterdir()):
                path.parent.rmdir()
    for p in AGENT_DIR.glob("*.md"):
        if generated(p):
            p.unlink()
    remove_block(RULES)
    if RULES.exists() and not RULES.read_text().strip():
        RULES.unlink()
    if dross:
        remove_block(DROSS_AGENTS)
    manifest_path = BASELINE / "manifest.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
    original = BASELINE / (manifest.get(str(OMP_AGENTS)) or "missing")
    span = section_span(original.read_text(), ROUTING_HEADING) if original.is_file() else None
    section = original.read_text()[span[0]:span[1]] if span else ""
    if OMP_AGENTS.exists():
        OMP_AGENTS.write_text(re.sub(BLOCK.pattern + r"\n*", lambda _: section, OMP_AGENTS.read_text(), count=1, flags=re.S))
    restored = []
    for raw, name in manifest.items():
        path = Path(raw)
        # Instruction files (RULES.md, and AGENTS.md wherever omp or Context kept it, including a Context home that
        # has since moved) keep later edits: only nstack's sections come out of them, never a whole-file restore.
        if name and not present(path) and path.name not in ("AGENTS.md", "RULES.md"):
            copy(BASELINE / name, path)
            restored.append(str(path.relative_to(HOME)))
    print("removed nstack" + (f"; restored {', '.join(restored)}" if restored else ""))


def load_yaml(text):
    try:
        import yaml
        return yaml.safe_load(text)
    except ImportError:  # omp ships with bun, which parses YAML natively
        js = "console.log(JSON.stringify(Bun.YAML.parse(await Bun.stdin.text()) ?? null))"
        run = subprocess.run(["bun", "-e", js], input=text, capture_output=True, text=True, check=True)
        return json.loads(run.stdout)


def catalog():
    """omp's model catalog as selector -> supported thinking levels, or None when omp is unavailable."""
    try:
        if CATALOG:
            data = json.loads(CATALOG.read_text())
        else:
            run = subprocess.run(["omp", "models", "--json"], capture_output=True, text=True, timeout=120)
            data = json.loads(run.stdout)
    except (OSError, ValueError, subprocess.TimeoutExpired):
        return None
    items = (data.get("catalog") or data.get("models", [])) if isinstance(data, dict) else data
    return {m["selector"]: m.get("thinking") or [] for m in items if m.get("selector")}


def model_problems(r):
    """Every roster model and default thinking level must exist in omp's catalog, so a typo or a model
    omp does not know yet fails here rather than at spawn time."""
    models = catalog()
    if models is None:
        print("WARN cannot run `omp models --json`; roster models not verified against omp's catalog")
        return []
    problems = []
    for name, a in r["agents"].items():
        if a["model"] not in models:
            problems.append(f"roster: {name}'s model {a['model']} is not in omp's catalog (`omp models`)")
        elif models[a["model"]] and a["thinking"] not in models[a["model"]]:
            problems.append(f"roster: {name}'s thinking {a['thinking']} is not one of {models[a['model']]}")
    return problems


def config_problems(r, skill_names):
    config = OMP / "config.yml"
    if not config.exists():
        return []
    try:
        cfg = load_yaml(config.read_text()) or {}
    except Exception as e:  # a parse failure makes the check meaningless, so it fails loudly
        return [f"cannot read {config}: {e}"]
    problems = []
    skills = cfg.get("skills") or {}
    if skills.get("enabled") is False:
        problems.append("config.yml sets skills.enabled: false")
    include, ignored = skills.get("includeSkills") or [], skills.get("ignoredSkills") or []
    disabled_ext = set(cfg.get("disabledExtensions") or [])
    for name in skill_names:
        if include and not any(fnmatchcase(name, pat) for pat in include):
            problems.append(f"config.yml includeSkills does not admit {name}")
        if any(fnmatchcase(name, pat) for pat in ignored) or f"skill:{name}" in disabled_ext:
            problems.append(f"config.yml excludes {name}")
    task = cfg.get("task") or {}
    disabled = set(task.get("disabledAgents") or [])
    overrides = task.get("agentModelOverrides") or {}
    for name, a in r["agents"].items():
        if name in disabled:
            problems.append(f"config.yml task.disabledAgents disables roster agent {name}")
        override = overrides.get(name)
        if override and THINKING_SUFFIX.sub("", override) != a["model"]:
            problems.append(f"config.yml task.agentModelOverrides.{name} selects {override}, expected {a['model']}")
    return problems


# omp's own model roles that run judgment or authoring work. Utility roles (smol, tiny, vision, web) are
# Nate's picks for cheap side jobs and stay outside the roster.
OMP_JUDGMENT_ROLES = ("default", "plan", "slow", "task", "advisor")
THINKING_SUFFIX = re.compile(r":(off|minimal|low|medium|high|xhigh|max|auto)$")


def config_warnings(r):
    """Warn when a native judgment role uses a model absent from the worker roster."""
    try:
        cfg = load_yaml((OMP / "config.yml").read_text()) or {}
    except Exception:
        return []  # config_problems reports an unreadable config
    roles = cfg.get("modelRoles") or {}
    used = {a["model"] for a in r["agents"].values()}
    advisor_on = (cfg.get("advisor") or {}).get("enabled") is True
    warnings = []
    for role in OMP_JUDGMENT_ROLES:
        value = roles.get(role)
        if not isinstance(value, str) or not value.strip() or value.startswith("@") or (role == "advisor" and not advisor_on):
            continue
        if THINKING_SUFFIX.sub("", value.strip()) not in used:
            warnings.append(f"config.yml modelRoles.{role} is {value}, a model no roster agent uses; change it with /model")
    return warnings


def check(dross):
    problems = []
    r = load_roster()
    problems += roster_problems(r)
    skill_names = [p.name for p, _ in links() if p.parent == SKILLS]
    for name in skill_names:
        text = (REPO / "skills" / name / "SKILL.md").read_text()
        m = re.search(r"^name:\s*(\S+)", text, re.M)
        if not m or m.group(1) != name:
            problems.append(f"skill {name}: frontmatter name does not match its directory")
        if len(text) > MAX_STANDARD_CHARS:
            problems.append(f"skill {name}: {len(text)} chars, over the {MAX_STANDARD_CHARS} standard cap")
    for path, source in links():
        if not (path.is_symlink() and path.resolve() == source.resolve()):
            problems.append(f"{path} is not linked to {source.relative_to(REPO)}")
    problems += [f"stale skill {p} is still installed" for p in SKILLS.glob("nstack*") if p.name not in skill_names]
    if not roster_problems(r):
        for name in r["agents"]:
            path, want = AGENT_DIR / f"{name}.md", agent_file(r, name)
            if not path.is_file() or path.read_text() != want:
                problems.append(f"{path} differs from the roster; rerun install.py")
                continue
            try:
                fm = load_yaml(want.split("\n---\n", 1)[0][4:])
                if fm.get("name") != name or not fm.get("description"):
                    problems.append(f"{path}: frontmatter does not parse to its name and description")
            except Exception as e:
                problems.append(f"{path}: frontmatter is not valid YAML ({e})")
        problems += [f"{p} was generated for an agent no longer in the roster" for p in stale_agents(r)]
        if not OMP_AGENTS.exists() or wrap(routing(r)) not in OMP_AGENTS.read_text():
            problems.append(f"{OMP_AGENTS} lacks the current routing section from the roster")
        targets = [(RULES, "omp-rules.md")]
        if dross and DROSS_AGENTS.exists():
            targets.append((DROSS_AGENTS, "dross.md"))
        elif dross:
            print("WARN", f"{DROSS_AGENTS} does not exist, so Dross's nstack block was not installed or checked")
        for path, source in targets:
            if not path.exists() or rendered(source, r) not in path.read_text():
                problems.append(f"{path} lacks the current block from {source}")
        problems += model_problems(r)
        problems += config_problems(r, skill_names)
        for w in config_warnings(r):
            print("WARN", w)
    for contract in CONTRACTS:
        if contract.exists():
            for task_type, name in json.loads(contract.read_text()).get("standards", {}).items():
                if name not in skill_names:
                    problems.append(f"{contract}: taskType {task_type} maps to {name}, which nstack does not ship")
    for p in problems:
        print("FAIL", p)
    print("ok" if not problems else f"{len(problems)} problem(s)")
    return not problems


